import { useEffect, useState } from 'react'
import Modal from './Modal.jsx'
import { version as currentVersion } from '../../package.json'

const STORAGE_KEY = 'orthobox:lastSeenVersion'

/**
 * `public/whats-new.json`'s highlights for the current version, or `null` if
 * there is nothing to show (missing file, a different version, no
 * highlights).
 */
function fetchHighlights() {
  return fetch('./whats-new.json')
    .then((response) => (response.ok ? response.json() : null))
    .then((data) => {
      if (!data || data.version !== currentVersion) return null
      return Array.isArray(data.highlights) && data.highlights.length > 0 ? data.highlights : null
    })
    .catch(() => null)
}

/**
 * "What's new" popup: shows the release highlights once on its own, the first
 * time the application runs on a version different from the one last recorded
 * — a first-ever visit only records the version, quietly, nothing to compare
 * it against yet. There is no button to reopen it: a real notification system
 * is for later.
 *
 * The highlights come from `public/whats-new.json`, a short, French,
 * user-facing summary regenerated by the release workflow for every
 * version — never the technical CHANGELOG.md. That generation step can fail
 * silently (see release-please.yml): when it does, nothing is shown.
 */
export default function WhatsNew() {
  const [content, setContent] = useState(null)

  useEffect(() => {
    let lastSeen
    try {
      lastSeen = window.localStorage.getItem(STORAGE_KEY)
    } catch {
      return undefined
    }

    if (lastSeen === null) {
      try {
        window.localStorage.setItem(STORAGE_KEY, currentVersion)
      } catch {
        /* Storage unavailable: nothing to track, nothing to show. */
      }
      return undefined
    }

    if (lastSeen === currentVersion) return undefined

    let active = true
    fetchHighlights().then((highlights) => {
      if (active && highlights) setContent(highlights)
    })
    return () => {
      active = false
    }
  }, [])

  const close = () => {
    setContent(null)
    try {
      window.localStorage.setItem(STORAGE_KEY, currentVersion)
    } catch {
      /* ignore */
    }
  }

  return (
    <>
      {content && (
        <Modal
          titleId="whats-new-title"
          title={`🎉 Nouveautés de la version ${currentVersion}`}
          onClose={close}
        >
          <ul className="whats-new__list">
            {content.map((line) => (
              <li key={line}>{line}</li>
            ))}
          </ul>
        </Modal>
      )}
    </>
  )
}
